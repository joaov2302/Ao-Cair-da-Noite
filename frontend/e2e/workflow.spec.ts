test('falha no salvamento e conflito preservam a edição local',async({page})=>{
  await register(page,'conflito-'+Date.now());
  await page.getByLabel('Nova campanha').fill('Teste de conflito');
  await page.getByRole('button',{name:'Criar como mestre'}).click();
  await expect(page.getByRole('button',{name:'Criar personagem'})).toBeEnabled();
  await page.getByRole('button',{name:'Criar personagem'}).click();
  await page.route('**/api/characters/*',async route=>{
    if(route.request().method()==='PATCH') return route.abort('failed');
    await route.continue();
  });
  await page.getByLabel('Nome do personagem',{exact:false}).fill('Edição preservada');
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByLabel('Nome do personagem',{exact:false})).toHaveValue('Edição preservada');
  await page.unroute('**/api/characters/*');
  await page.getByRole('button',{name:'Salvar agora'}).click();
  await saved(page);
  await page.route('**/api/characters/*',async route=>{
    if(route.request().method()==='PATCH') return route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:'Conflito de teste'})});
    await route.continue();
  });
  await page.getByLabel('Nome do personagem',{exact:false}).fill('Alteração em conflito');
  await expect(page.locator('.save-actions')).toContainText('Conflito de edição');
  await expect(page.getByLabel('Nome do personagem',{exact:false})).toHaveValue('Alteração em conflito');
  await expect(page.getByRole('button',{name:'Ver versão salva'})).toBeVisible();
});
