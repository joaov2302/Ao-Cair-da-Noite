import { test, expect, type Page } from '@playwright/test';
import fs from 'node:fs/promises';

async function register(page:Page, username:string) {
  await page.goto('/');
  await page.getByRole('button',{name:'Ainda não tenho conta'}).click();
  await page.getByLabel('Usuário',{exact:true}).fill(username);
  await page.getByLabel('Senha',{exact:false}).fill('Caderno-Teste-2026!');
  await page.getByRole('button',{name:'Criar minha conta'}).click();
  await expect(page.getByRole('heading',{name:'Meu caderno',exact:true})).toBeVisible();
}
async function saved(page:Page) {
  await expect(page.locator('.save-actions')).toContainText('Salvo',{timeout:10000});
}
async function step(page:Page, name:string) {
  await page.getByRole('navigation',{name:'Etapas de criação'}).getByRole('button',{name:new RegExp(name+'$')}).click();
}

